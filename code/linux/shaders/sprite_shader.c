#include "sprite_shader.h"

const char * const spriteVertexSource = 
"struct screen_dims { \n"
"    float width; \n"
"    float height; \n"
"}; \n"
"uniform screen_dims screenDims; \n"
" \n"
"attribute vec3 pos; \n"
"attribute vec2 texCoords; \n"
"attribute vec4 color; \n"
"attribute float textureID; \n"
" \n"
"varying vec2 vTexCoords; \n"
"varying vec4 vColor; \n"
"varying float vTextureID; \n"
" \n"
"void main() { \n"
"    gl_Position = vec4(pos.x * (1.0 / screenDims.width) * 2.0 - 1.0, \n"
"                    pos.y * (1.0 / screenDims.height) * 2.0 - 1.0, \n"
"                    -1.0, 1.0); \n"
"    gl_Position.y = -gl_Position.y; \n"
"    vTexCoords = texCoords; \n"
"    vColor = color; \n"
"    vTextureID = textureID; \n"
"} \n";

const char * const spriteFragmentSource = 
"#extension GL_OES_standard_derivatives : enable \n "
" \n "
"uniform sampler2D texture0; \n "
"uniform sampler2D texture1; \n "
"uniform sampler2D texture2; \n "
"uniform sampler2D texture3; \n "
"uniform sampler2D texture4; \n "
"uniform sampler2D texture5; \n "
"uniform sampler2D texture6; \n "
"uniform sampler2D texture7; \n "
" \n "
"uniform vec2 texture0Size; \n "
"uniform vec2 texture1Size; \n "
"uniform vec2 texture2Size; \n "
"uniform vec2 texture3Size; \n "
"uniform vec2 texture4Size; \n "
"uniform vec2 texture5Size; \n "
"uniform vec2 texture6Size; \n "
"uniform vec2 texture7Size; \n "
" \n "
"varying vec2 vTexCoords; \n "
"varying vec4 vColor; \n "
"varying float vTextureID; \n "
" \n "
"void main() { \n "
"    vec4 baseColor; \n "
" \n "
"    vec2 texSize; \n "
"    vec2 uv = vTexCoords; \n "
" \n "
"    if (vTextureID < 0.5) { \n "
"        texSize = texture0Size; \n "
"    } \n "
"    else if (vTextureID >= 0.5 && vTextureID < 1.5) { \n "
"        texSize = texture1Size; \n "
"    } \n "
"    else if (vTextureID >= 1.5 && vTextureID < 2.5) { \n "
"        texSize = texture2Size; \n "
"    } \n "
"    else if (vTextureID >= 2.5 && vTextureID < 3.5) { \n "
"        texSize = texture3Size; \n "
"    } \n "
"    else if (vTextureID >= 3.5 && vTextureID < 4.5) { \n "
"        texSize = texture4Size; \n "
"    } \n "
"    else if (vTextureID >= 4.5 && vTextureID < 5.5) { \n "
"        texSize = texture5Size; \n "
"    } \n "
"    else if (vTextureID >= 5.5 && vTextureID < 6.5) { \n "
"        texSize = texture6Size; \n "
"    } \n "
"    else { \n "
"        texSize = texture7Size; \n "
"    } \n "
" \n "
"    uv *= texSize; \n "
"    vec2 seam = floor(uv + 0.5); \n "
"    vec2 dudv = fwidth(uv); \n "
"    uv = seam + clamp((uv - seam) / dudv, -0.5, 0.5); \n "
"    uv /= texSize; \n "
" \n "
"    if (vTextureID < 0.5) { \n "
"        baseColor = texture2D(texture0, uv); \n "
"    } \n "
"    else if (vTextureID >= 0.5 && vTextureID < 1.5) { \n "
"        baseColor = texture2D(texture1, uv); \n "
"    } \n "
"    else if (vTextureID >= 1.5 && vTextureID < 2.5) { \n "
"        baseColor = texture2D(texture2, uv); \n "
"    } \n "
"    else if (vTextureID >= 2.5 && vTextureID < 3.5) { \n "
"        baseColor = texture2D(texture3, uv); \n "
"    } \n "
"    else if (vTextureID >= 3.5 && vTextureID < 4.5) { \n "
"        baseColor = texture2D(texture4, uv); \n "
"    } \n "
"    else if (vTextureID >= 4.5 && vTextureID < 5.5) { \n "
"        baseColor = texture2D(texture5, uv); \n "
"    } \n "
"    else if (vTextureID >= 5.5 && vTextureID < 6.5) { \n "
"        baseColor = texture2D(texture6, uv); \n "
"    } \n "
"    else { \n "
"        baseColor = texture2D(texture7, uv); \n "
"    } \n "
" \n "
"    gl_FragColor = baseColor * vColor; \n "
"}";
