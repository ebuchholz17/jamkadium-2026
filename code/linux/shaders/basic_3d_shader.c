
const char * const basic3DVertexSource =
"attribute vec3 position; \n "
"attribute vec2 texCoords; \n "
" \n "
"uniform mat4 modelMatrix; \n "
"uniform mat4 viewMatrix; \n "
"uniform mat4 projMatrix; \n "
" \n "
"varying vec2 vTexCoords; \n "
"varying float vFogAmount; \n "
" \n "
"void main() { \n "
"    vec4 cameraPos = viewMatrix * modelMatrix * vec4(position, 1.0);  \n "
"    gl_Position = projMatrix * cameraPos; \n "
"    vTexCoords = texCoords; \n "
" \n "
"    vFogAmount = cameraPos.z; \n "
"} \n ";


const char * const basic3DFragmentSource = 
"//#extension GL_OES_standard_derivatives : enable \n "
" \n "
"varying vec2 vTexCoords; \n "
"varying float vFogAmount; \n "
" \n "
"uniform sampler2D texture; \n "
" \n "
"void main() { \n "
"    vec2 texSize = vec2(4096.0, 4096.0); \n "
"    vec2 uv = vTexCoords; \n "
"    uv *= texSize; \n "
"    vec2 seam = floor(uv + 0.5); \n "
"    vec2 dudv = fwidth(uv); \n "
"    uv = seam + clamp((uv - seam) / dudv, -0.5, 0.5); \n "
"    uv /= texSize; \n "
" \n "
"    vec3 textureColor = texture2D(texture, uv).rgb; \n "
" \n "
"    vec3 fogColor = vec3(0.144, 0.41, 0.90); \n "
"    float fogFactor = clamp(1.0 - vFogAmount / -900.0, 0.0, 1.0); \n "
"    vec3 foggedColor = fogFactor * textureColor + (1.0 - fogFactor) * fogColor; \n "
"    gl_FragColor = vec4(foggedColor, 1.0); \n "
"} \n ";
